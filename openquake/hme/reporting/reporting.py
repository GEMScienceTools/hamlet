def render_rupture_matching_eval(
    env: Environment, cfg: dict, input_data: dict, results: dict
) -> None:

    if "map_epsg" in cfg["report"]["basic"].keys():
        map_epsg = cfg["report"]["basic"]["map_epsg"]
    else:
        map_epsg = None

    # Get save_plot parameter from config
    test_config = cfg["config"]["model_framework"]["gem"][
        "rupture_matching_eval"
    ]
    save_plot = test_config.get("save_plot", False)

    rup_match_env = env.get_template("rupture_matching_eval.html")

    rup_match_results = results["gem"]["rupture_matching_eval"]["val"]

    mag_dist_plot_str = plot_rup_match_mag_dist(
        rup_match_results["matched_rups"],
        input_data["eq_gdf"],
        save_fig=save_plot,
    )

    rup_match_map = plot_rup_match_map(
        input_data["eq_gdf"],
        rup_match_results["matched_rups"],
        rup_match_results["unmatched_eqs"],
        map_epsg=map_epsg,
        return_str=True,
        save_fig=save_plot,
    )

    rup_match_json = prepare_rup_match_data_for_d3(
        input_data["eq_gdf"],
        rup_match_results["matched_rups"],
        rup_match_results["unmatched_eqs"],
        map_epsg=map_epsg,
    )

    if len(rup_match_results["unmatched_eqs"]) > 0:
        unmatched_eq_table_str = rup_match_results["unmatched_eqs"].to_html()
    else:
        unmatched_eq_table_str = "None"

    results["gem"]["rupture_matching_eval"]["rendered_text"] = (
        rup_match_env.render(
            res=rup_match_results,
            mag_dist_plot_str=mag_dist_plot_str,
            unmatched_eq_table_str=unmatched_eq_table_str,
            # map_str=rup_match_map,
            earthquake_data=json.dumps(rup_match_json),
        )
    )


def render_mfd_eval(env: Environment, cfg: dict, results: dict):
    from openquake.hme.utils import get_mag_duration_from_comp_table

    test_config = cfg["config"]["model_framework"]["gem"]["model_mfd"]
    test_data = results["gem"]["model_mfd"]["val"]["test_data"]
    mfd_df = test_data["mfd_df"]
    annualize = test_data.get("annualize", True)

    completeness_table = cfg["input"]["seis_catalog"].get("completeness_table")
    stop_date = cfg["input"]["seis_catalog"].get("stop_date")

    # Calculate per-bin durations if completeness table is present
    if completeness_table is not None and annualize:
        t_yrs = {
            mag: get_mag_duration_from_comp_table(
                completeness_table, mag, stop_date
            )
            for mag in mfd_df.index
        }
    else:
        t_yrs = test_config.get("investigation_time")
        if t_yrs is None:
            t_yrs = cfg["input"]["seis_catalog"].get("duration", 1.0)

    # Get save_plot parameter from config
    save_plot = test_config.get("save_plot", False)

    results["gem"]["model_mfd"]["val"]["mfd_plot"] = plot_mfd(
        model=mfd_df["mod_mfd_cum"].to_dict(),
        observed=mfd_df["obs_mfd_cum"].to_dict(),
        t_yrs=t_yrs,
        return_fig=False,
        return_string=True,
        annualize=annualize,
        save_fig=save_plot,
    )

    mfd_template = env.get_template("mfd.html")
    results["gem"]["model_mfd"]["rendered_text"] = mfd_template.render(
        cfg=cfg, results=results
    )


def render_cumulative_occurrence_eval(
    env: Environment, cfg: dict, results: dict
):
    eval_results = results["gem"]["cumulative_occurrence_eval"]["val"]

    # Get save_plot parameter from config
    test_config = cfg["config"]["model_framework"]["gem"][
        "cumulative_occurrence_eval"
    ]
    save_plot = test_config.get("save_plot", False)

    # If save_plot is requested, generate and save matplotlib version
    if save_plot:
        plot_eqs_by_mag_time(
            eval_results["eqs_by_mag_time"],
            model_mfd=eval_results["model_mfd"],
            return_str=False,
            save_fig=save_plot,
        )

    prepped_data, start_date, stop_date = prepare_eqs_by_mag_time_for_d3(
        eval_results["eqs_by_mag_time"], model_mfd=eval_results["model_mfd"]
    )

    json_data = json.dumps(prepped_data).strip("'")

    cum_occ_template = env.get_template("cumulative_occurrence.html")
    results["gem"]["cumulative_occurrence_eval"]["rendered_text"] = (
        cum_occ_template.render(earthquake_data=json_data)
    )


def render_catalog_ground_motion_eval(
    env: Environment, cfg: dict, results: dict
):
    eval_results = results["gem"]["catalog_ground_motion_eval"]["val"]

    # Get save_plot parameter from config
    test_config = cfg["config"]["model_framework"]["gem"][
        "catalog_ground_motion_eval"
    ]
    save_plot = test_config.get("save_plot", False)

    res_plots = {}

    for trt, gmm_comp in eval_results["gmm_comparisons"].items():
        res_plots[trt] = []
        plot = plot_PGA_distance(gmm_comp, trt, save_fig=save_plot)
        if plot:
            res_plots[trt].append(plot)
        plot = plot_PGA_scatter(gmm_comp, trt, save_fig=save_plot)
        if plot:
            res_plots[trt].append(plot)

    cat_gm_template = env.get_template("catalog_ground_motion_eval.html")

    results["gem"]["catalog_ground_motion_eval"]["rendered_text"] = (
        cat_gm_template.render(res_plots=res_plots)
    )
